const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const sharp = require('../../server/node_modules/sharp')
const {processImages} = require('../../scripts/resize-server-images.cjs')

test('图片工具居中cover裁剪、保留格式和备份；预览和重复运行不改原图', async t => {
    const prefix = path.resolve('.image-tool-test-')
    const directory = await fs.mkdtemp(prefix)
    t.after(async () => {
        assert.ok(path.resolve(directory).startsWith(path.resolve(prefix)))
        await fs.rm(directory, {recursive: true, force: true})
    })
    const solid = color => sharp({create: {width: 100, height: 100, channels: 3, background: color}}).png().toBuffer()
    const stripes = await sharp({create: {width: 300, height: 100, channels: 3, background: 'red'}})
        .composite([{input: await solid('green'), left: 100, top: 0}, {input: await solid('blue'), left: 200, top: 0}]).png().toBuffer()
    await fs.mkdir(path.join(directory, 'nested'))
    await fs.writeFile(path.join(directory, 'wide.png'), stripes)
    const jpeg = await sharp({create: {width: 60, height: 140, channels: 3, background: 'orange'}}).jpeg().withMetadata({orientation: 6}).toBuffer()
    await fs.writeFile(path.join(directory, 'nested/tall.jpg'), jpeg)
    await fs.writeFile(path.join(directory, 'metadata.json'), '{}')
    const messages = [], log = message => messages.push(message)
    const preview = await processImages(directory, {dryRun: true, log})
    assert.equal(preview.processed, 2)
    assert.equal(preview.backupDirectory, null)
    assert.deepEqual(await fs.readFile(path.join(directory, 'wide.png')), stripes)
    const first = await processImages(directory, {log})
    assert.equal(first.processed, 2, messages.join('\n'))
    assert.equal(first.failed, 0)
    assert.deepEqual(await fs.readFile(path.join(first.backupDirectory, 'wide.png')), stripes)
    assert.deepEqual(await fs.readFile(path.join(first.backupDirectory, 'nested/tall.jpg')), jpeg)
    for (const [filename, format] of [['wide.png', 'png'], ['nested/tall.jpg', 'jpeg']]) {
        const metadata = await sharp(path.join(directory, filename)).metadata()
        assert.equal(metadata.width, 100)
        assert.equal(metadata.height, 100)
        assert.equal(metadata.format, format)
        assert.equal(metadata.orientation, undefined)
    }
    const pixel = await sharp(path.join(directory, 'wide.png')).raw().toBuffer()
    assert.deepEqual(Array.from(pixel.subarray(0, 3)), [0, 128, 0])
    const saved = await fs.readFile(path.join(directory, 'wide.png'))
    const again = await processImages(directory, {log})
    assert.equal(again.processed, 0)
    assert.equal(again.skipped, 2)
    assert.deepEqual(await fs.readFile(path.join(directory, 'wide.png')), saved)
    await fs.writeFile(path.join(directory, 'broken.jpg'), 'not an image')
    const invalid = await processImages(directory, {log})
    assert.equal(invalid.failed, 1)
    assert.equal(await fs.readFile(path.join(directory, 'broken.jpg'), 'utf8'), 'not an image')
    assert.equal(await fs.readFile(path.join(directory, 'metadata.json'), 'utf8'), '{}')
})
