require('../../scripts/typescript.cjs')
const test = require('node:test')
const assert = require('node:assert/strict')
const {DiningScenario} = require('../support/DiningScenario.ts')
const {ReferenceDiningCatalog} = require('../../src/composition/ReferenceDiningCatalog.ts')
const {DiningQueries} = require('../../src/infrastructure/query/DiningQueries.ts')
const {InitializeDiningUseCase} = require('../../src/coordination/application/port/in/initialization/InitializeDiningUseCase.ts')

test('启动更新已有公共菜单后可重新加入含新增菜品的房间，保留点菜且不上传公开菜单', async t => {
    const bundled = ReferenceDiningCatalog.restaurants(), current = bundled.find(restaurant => restaurant.id === 'niuniu')
    const host = await new DiningScenario.Meal().givenRestaurant(current)
    t.after(host.app.dispose)
    await host.createRoom('room', '123456', 20000, 'sukiyaki')
    await host.whenEating(2, 'niuniu', 'shrimp')
    const guest = await new DiningScenario.Meal(host.relay, 'guest').givenRestaurant({...current,
        products: current.products.filter(product => product.id === 'beef')})
    t.after(guest.app.dispose)
    await guest.joinRoom('room')
    const invalid = guest.app.queries.bind(DiningQueries.Result, () => ({session: guest.dining.session(), actor: guest.dining.identity(), restaurantId: 'niuniu'}))
    await new Promise(resolve => setImmediate(resolve))
    assert.match(invalid.error.value.message, /CATALOG_RECONCILIATION_REQUIRED/)
    invalid.dispose()
    await guest.leave()
    const original = DiningScenario.restaurant({id: 'personal', name: '我的私人菜单'})
    await guest.givenRestaurant(original)
    const sent = host.relay.sent
    const initialize = guest.app.resolve(InitializeDiningUseCase.token)
    const request = new InitializeDiningUseCase.Request(bundled)
    await initialize.execute(request)
    assert.equal(guest.app.catalog.restaurant('niuniu').products.some(product => product.id === 'shrimp'), true)
    assert.equal(guest.app.catalog.restaurant('niuniu').version, 2)
    assert.equal(guest.app.catalog.restaurant('personal').name, original.name)
    assert.equal(guest.app.catalog.restaurant('personal').version, original.version)
    assert.equal(host.relay.sent, sent)
    await guest.joinRoom('room')
    assert.equal(guest.dining.preview('niuniu').foodValueMinor, 2 * current.products.find(product => product.id === 'shrimp').priceMinor)
    guest.thenQuantityIs(2, 'niuniu', 'shrimp')
    await initialize.execute(request)
    assert.equal(guest.app.catalog.restaurant('niuniu').version, 2)
    assert.equal(host.relay.catalogs.size, 0)
    assert.equal(host.relay.streams.get('room').flatMap(batch => batch.events).some(event => event.type === 'RestaurantPublished'), false)
})

test('公共菜单内容更新时以本地连续版本发布，并对进行中的单人消费对账', async t => {
    const current = ReferenceDiningCatalog.restaurants().find(restaurant => restaurant.id === 'niuniu')
    const cached = {...current, products: [
        ...current.products, {id: 'removed', categoryId: current.categories[0].id, name: '已下架菜品', priceMinor: 100}
    ]}
    const meal = await new DiningScenario.Meal().givenRestaurant(cached)
    t.after(meal.app.dispose)
    await meal.givenRestaurant({...cached, version: 2})
    await meal.startSingle(20000, 'sukiyaki')
    await meal.whenEating(1, 'niuniu', 'removed')
    await meal.app.resolve(InitializeDiningUseCase.token).execute(new InitializeDiningUseCase.Request([current]))
    assert.equal(meal.app.catalog.restaurant('niuniu').version, 3)
    meal.thenQuantityIs(0, 'niuniu', 'removed')
    assert.equal(meal.dining.preview('niuniu').foodValueMinor, 0)
})
